use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use write_fonts::read::tables::glyf::CurvePoint;
use write_fonts::tables::glyf::{Contour, Glyph, SimpleGlyph};

